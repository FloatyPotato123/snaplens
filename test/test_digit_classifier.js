function classifyCostDigit(digitMask) {
    let bestDigit = 1, bestDice = -1;
    for (const [digitStr, tmpl] of Object.entries(digitTemplates)) {
        const d = parseInt(digitStr, 10);
        let maxDice = 0;
        let tOnes = 0;
        for (let i = 0; i < 256; i++) if (tmpl[i]) tOnes++;

        // Small 2D shift (+- 2px)
        for (let dy = -2; dy <= 2; dy++) {
            for (let dx = -2; dx <= 2; dx++) {
                let inter = 0, qOnes = 0;
                for (let y = 0; y < 16; y++) {
                    const ty = y + dy;
                    if (ty < 0 || ty >= 16) continue;
                    for (let x = 0; x < 16; x++) {
                        const tx = x + dx;
                        if (tx < 0 || tx >= 16) continue;
                        const qBit = digitMask[y * 16 + x];
                        const tBit = tmpl[ty * 16 + tx];
                        if (qBit) qOnes++;
                        if (qBit && tBit) inter++;
                    }
                }
                const dice = (2 * inter) / (qOnes + tOnes + 1e-5);
                if (dice > maxDice) maxDice = dice;
            }
        }
        if (maxDice > bestDice) {
            bestDice = maxDice;
            bestDigit = d;
        }
    }
    return { cost: bestDigit, confidence: bestDice };
}

